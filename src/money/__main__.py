"""Build every table, chart and the results write-up from the cached data.

    python -m money.fetch   # once: download from BLS and BEA into data/raw
    python -m money         # analysis -> outputs/
"""

from __future__ import annotations

import json
from pathlib import Path

from . import analysis, charts
from .fetch import CPI_END, CPI_START, RAW_DIR

OUT = Path(__file__).resolve().parents[2] / "outputs"


def main(raw_dir: Path = RAW_DIR, out: Path = OUT) -> None:
    OUT = out
    (OUT / "tables").mkdir(parents=True, exist_ok=True)
    (OUT / "figures").mkdir(parents=True, exist_ok=True)

    monthly, rpp = analysis.load_cached(raw_dir)
    annual = analysis.annual_average(monthly)
    pp = analysis.purchasing_power(annual, CPI_START, CPI_END)
    yoy = analysis.yoy_inflation(annual)

    annual.round(3).to_csv(OUT / "tables" / "cpi_annual.csv", index=False)
    pp.round(2).to_csv(OUT / "tables" / "purchasing_power.csv", index=False)
    yoy.round(2).to_csv(OUT / "tables" / "inflation_yoy.csv", index=False)

    charts.purchasing_power_bar(pp, CPI_START, CPI_END, OUT / "figures" / "purchasing_power.png")
    charts.yoy_line(yoy, analysis.FED_TARGET_PCT, OUT / "figures" / "inflation_yoy.png")

    incomplete = annual[annual["months"] < 12]
    p = pp.set_index("category")
    summary = {
        "cpi_years": [CPI_START, CPI_END],
        "cents_per_2015_dollar": p["cents_per_base_dollar"].round(1).to_dict(),
        "cost_in_end_year_of_100_base_dollars": round(p.loc["All items", "cost_of_base_100"], 2),
        "peak_inflation": yoy.loc[yoy["yoy_pct"].idxmax(), ["year", "yoy_pct"]].to_dict(),
        "years_above_fed_target": yoy.loc[yoy["above_fed_target"], "year"].tolist(),
        "incomplete_years": sorted({int(y) for y in incomplete["year"]}),
    }

    if rpp is not None:
        last = int(rpp["year"].max())
        rs = analysis.rpp_summary(rpp)
        rs.round(2).to_csv(OUT / "tables" / "rpp_by_state.csv", index=False)
        charts.rpp_tile_map(rs, last, OUT / "figures" / "rpp_tile_map.png")
        charts.rpp_extremes_bar(rs, last, OUT / "figures" / "rpp_extremes.png")
        summary["rpp_year"] = last
        summary["most_expensive"] = rs.head(3)[["state", f"rpp_{last}"]].values.tolist()
        summary["least_expensive"] = rs.tail(3)[["state", f"rpp_{last}"]].values.tolist()
        summary["rpp_spread_pts"] = round(rs[f"rpp_{last}"].max() - rs[f"rpp_{last}"].min(), 1)
        summary["n_states"] = len(rs)

    (OUT / "summary.json").write_text(json.dumps(summary, indent=2, default=float))
    (OUT / "RESULTS.md").write_text(write_results(summary, pp, yoy))
    print(json.dumps(summary, indent=2, default=float))


def write_results(s: dict, pp, yoy) -> str:
    """Results page generated from the data, so every number comes from the run."""
    base, end = s["cpi_years"]
    lines = [
        "# Results",
        "",
        "_Generated by `python -m money` from the data in `data/raw/`. Do not edit by hand._",
        "",
        f"## How far a {base} dollar goes in {end}",
        "",
        "![Purchasing power](figures/purchasing_power.png)",
        "",
        f"| Category | Prices up | $1 of {base} spending buys in {end} |",
        "|---|---|---|",
    ]
    for _, r in pp.iterrows():
        lines.append(f"| {r['category']} | {r['price_change_pct']:.1f}% | {r['cents_per_base_dollar']:.0f}¢ |")
    lines += [
        "",
        f"A basket that cost $100 in {base} costs ${s['cost_in_end_year_of_100_base_dollars']:.2f} in {end}.",
        "",
        "## Inflation year over year",
        "",
        "![Inflation](figures/inflation_yoy.png)",
        "",
        f"Inflation peaked at {s['peak_inflation']['yoy_pct']:.1f}% in {int(s['peak_inflation']['year'])}. "
        f"It was above the Fed's 2% target in {len(s['years_above_fed_target'])} of {len(yoy)} years "
        f"({', '.join(str(y) for y in s['years_above_fed_target'])}).",
    ]
    if s["incomplete_years"]:
        lines += [
            "",
            f"Note: annual averages for {', '.join(map(str, s['incomplete_years']))} use fewer than 12 months, "
            "because BLS published no data for some months (see `tables/cpi_annual.csv`, column `months`).",
        ]
    if "rpp_year" in s:
        y = s["rpp_year"]
        most = ", ".join(f"{st} ({v:.1f})" for st, v in s["most_expensive"])
        least = ", ".join(f"{st} ({v:.1f})" for st, v in s["least_expensive"])
        lines += [
            "",
            f"## Cost of living by state, {y}",
            "",
            "![RPP map](figures/rpp_tile_map.png)",
            "",
            "![RPP extremes](figures/rpp_extremes.png)",
            "",
            f"Most expensive: {most}. Least expensive: {least}. "
            f"The gap between the most and least expensive is {s['rpp_spread_pts']} points.",
        ]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    main()
